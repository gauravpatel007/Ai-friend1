const RECENT_EMOJIS_STORAGE_KEY = 'bond_recent_emojis';
const MAX_RECENT_COUNT = 24;

export const getRecentEmojis = (): string[] => {
  try {
    const raw = localStorage.getItem(RECENT_EMOJIS_STORAGE_KEY);
    if (!raw) return ['😀', '🔥', '✨', '👍', '❤️', '🎉', '🤖', '🚀'];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : ['😀', '🔥', '✨', '👍', '❤️', '🎉', '🤖', '🚀'];
  } catch {
    return ['😀', '🔥', '✨', '👍', '❤️', '🎉', '🤖', '🚀'];
  }
};

export const saveRecentEmoji = (emoji: string): string[] => {
  try {
    const current = getRecentEmojis();
    const updated = [emoji, ...current.filter((e) => e !== emoji)].slice(0, MAX_RECENT_COUNT);
    localStorage.setItem(RECENT_EMOJIS_STORAGE_KEY, JSON.stringify(updated));
    return updated;
  } catch {
    return [emoji];
  }
};

export const searchEmojis = (query: string): EmojiItem[] => {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) return ALL_EMOJIS;

  return ALL_EMOJIS.filter((item) => {
    if (item.name.toLowerCase().includes(cleanQ)) return true;
    if (item.emoji.includes(cleanQ)) return true;
    return item.keywords.some((kw) => kw.toLowerCase().includes(cleanQ));
  });
};
